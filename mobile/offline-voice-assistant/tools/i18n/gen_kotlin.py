#!/usr/bin/env python3
"""Generates brain/.../Translations.kt from tools/i18n/<code>.json (edit the JSON, not the Kotlin)."""
import json

OUT = "brain/src/main/kotlin/com/binisog/voiceassistant/brain/Translations.kt"


def k(s):
    return json.dumps(s, ensure_ascii=False).replace("$", "\\$")


def klist(xs):
    return "listOf(" + ", ".join(k(x) for x in xs) + ")"


def kmap(d, fn=k):
    return "mapOf(" + ", ".join(f"{k(a)} to {fn(b)}" for a, b in d.items()) + ")"


import sys

# Languages to include (the JSON drafts for om/ti/aa are kept in tools/i18n but are not enabled).
ENABLED = sys.argv[1:]
packs = []
for code in ENABLED:
    d = json.load(open(f"tools/i18n/{code}.json", encoding="utf-8"))
    n = d["numbers"]
    ui = d["ui"] if isinstance(d["ui"], dict) else {}
    packs.append(f"""        "{code}" to Pack(
            prompts = {kmap(d["prompts"], klist)},
            faqAnswers = {klist([f["answer"] for f in d["faq"]])},
            faqKeywords = listOf({", ".join(klist(f["keywords"]) for f in d["faq"])}),
            accountTypes = {kmap(d["accountTypes"])},
            intents = {kmap(d["intents"], klist)},
            namePrefixes = {klist(d["namePrefixes"])},
            nameSuffixes = {klist(d["nameSuffixes"])},
            placeFillers = {klist(d["placeFillers"])},
            editKeys = {kmap(d["editKeys"], klist)},
            languageNames = {klist(d["languageNames"])},
            bankName = {k(d["bankName"])},
            agentName = {k(d["agentName"])},
            units = {klist(n["units"])},
            tens = {klist(n["tens"])},
            teenPrefix = {k(n.get("teenPrefix", "").strip())},
            hundred = {k(n["hundred"])},
            thousand = {k(n["thousand"])},
            multiplierAfter = {str(bool(n.get("multiplierAfter"))).lower()},
            conjunction = {k(n.get("conjunction", ""))},
            months = {klist(d["months"])},
            ui = {kmap(ui)},
        )""")

open(OUT, "w", encoding="utf-8").write(f"""// GENERATED by tools/i18n/gen_kotlin.py from tools/i18n/*.json – do not edit by hand.
package com.binisog.voiceassistant.brain

/** Afaan Oromoo, Tigrinya and Afar texts (drafted with Gemini; to be reviewed by native speakers). */
object Translations {{
    class Pack(
        val prompts: Map<String, List<String>>,
        val faqAnswers: List<String>,
        val faqKeywords: List<List<String>>,
        val accountTypes: Map<String, String>,
        val intents: Map<String, List<String>>,
        val namePrefixes: List<String>,
        val nameSuffixes: List<String>,
        val placeFillers: List<String>,
        val editKeys: Map<String, List<String>>,
        val languageNames: List<String>,
        val bankName: String,
        val agentName: String,
        val units: List<String>,
        val tens: List<String>,
        val teenPrefix: String,
        val hundred: String,
        val thousand: String,
        val multiplierAfter: Boolean,
        val conjunction: String,
        val months: List<String>,
        val ui: Map<String, String>,
    )

    val packs: Map<String, Pack> by lazy {{
        mapOf<String, Pack>(
{(","+chr(10)).join(packs)}
        )
    }}

    fun of(lang: Lang): Pack? = packs[lang.code]
}}
""")
print("wrote", OUT)
